def find_node(node, target_name):
    if isinstance(node, dict):
        if node.get('name') == target_name:
            return node
        for v in node.values():
            r = find_node(v, target_name)
            if r is not None:
                return r
    elif isinstance(node, list):
        for v in node:
            r = find_node(v, target_name)
            if r is not None:
                return r
    return None

